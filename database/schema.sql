-- SportSee étape 2 — PostgreSQL. Les données Excel sont des agrégats joueur/équipe,
-- sans saison explicite ni identifiants de match : aucune ligne de match n'est créée.
CREATE TABLE IF NOT EXISTS teams (
    team_code CHAR(3) PRIMARY KEY,
    team_name TEXT NOT NULL UNIQUE,
    CONSTRAINT ck_teams_code_upper CHECK (team_code ~ '^[A-Z]{3}$')
);

CREATE TABLE IF NOT EXISTS players (
    player_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_name TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_players_name_nonblank CHECK (length(btrim(source_name)) > 0)
);

-- Une rangée = agrégat fourni pour le joueur dans une équipe, non une performance de match.
-- season_label reste NULL car le classeur ne documente aucune saison. dataset_key distingue
-- des imports/snapshots et forme avec joueur+équipe une clé d'upsert reproductible.
CREATE TABLE IF NOT EXISTS stats (
    stats_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id BIGINT NOT NULL REFERENCES players(player_id) ON DELETE CASCADE,
    team_code CHAR(3) NOT NULL REFERENCES teams(team_code),
    season_label TEXT,
    dataset_key TEXT NOT NULL,
    age SMALLINT NOT NULL CHECK (age BETWEEN 0 AND 120),
    gp SMALLINT NOT NULL CHECK (gp BETWEEN 0 AND 82),
    wins SMALLINT NOT NULL CHECK (wins >= 0),
    losses SMALLINT NOT NULL CHECK (losses >= 0),
    minutes NUMERIC(12,4) NOT NULL,
    points INTEGER NOT NULL CHECK (points >= 0),
    field_goals_made INTEGER NOT NULL CHECK (field_goals_made >= 0),
    field_goals_attempted INTEGER NOT NULL CHECK (field_goals_attempted >= 0),
    field_goal_pct NUMERIC(12,4) NOT NULL,
    metric_15_00 INTEGER NOT NULL,
    three_pointers_attempted INTEGER NOT NULL CHECK (three_pointers_attempted >= 0),
    three_point_pct NUMERIC(12,4) NOT NULL,
    free_throws_made INTEGER NOT NULL CHECK (free_throws_made >= 0),
    free_throws_attempted INTEGER NOT NULL CHECK (free_throws_attempted >= 0),
    free_throw_pct NUMERIC(12,4) NOT NULL,
    offensive_rebounds INTEGER NOT NULL CHECK (offensive_rebounds >= 0),
    defensive_rebounds INTEGER NOT NULL CHECK (defensive_rebounds >= 0),
    rebounds INTEGER NOT NULL CHECK (rebounds >= 0),
    assists INTEGER NOT NULL CHECK (assists >= 0),
    turnovers INTEGER NOT NULL CHECK (turnovers >= 0),
    steals INTEGER NOT NULL CHECK (steals >= 0),
    blocks INTEGER NOT NULL CHECK (blocks >= 0),
    personal_fouls INTEGER NOT NULL CHECK (personal_fouls >= 0),
    fantasy_points INTEGER NOT NULL,
    double_doubles INTEGER NOT NULL CHECK (double_doubles >= 0),
    triple_doubles INTEGER NOT NULL CHECK (triple_doubles >= 0),
    plus_minus NUMERIC(12,4) NOT NULL,
    off_rating NUMERIC(12,4) NOT NULL,
    def_rating NUMERIC(12,4) NOT NULL,
    net_rating NUMERIC(12,4) NOT NULL,
    assist_pct NUMERIC(12,4) NOT NULL,
    assist_to_turnover NUMERIC(12,4) NOT NULL,
    assist_ratio NUMERIC(12,4) NOT NULL,
    offensive_rebound_pct NUMERIC(12,4) NOT NULL,
    defensive_rebound_pct NUMERIC(12,4) NOT NULL,
    rebound_pct NUMERIC(12,4) NOT NULL,
    turnover_ratio NUMERIC(12,4) NOT NULL,
    effective_fg_pct NUMERIC(12,4) NOT NULL,
    true_shooting_pct NUMERIC(12,4) NOT NULL,
    usage_pct NUMERIC(12,4) NOT NULL,
    pace NUMERIC(12,4) NOT NULL,
    pie NUMERIC(12,4) NOT NULL,
    possessions INTEGER NOT NULL CHECK (possessions >= 0),
    source_file TEXT NOT NULL,
    source_sheet TEXT NOT NULL,
    source_row INTEGER NOT NULL CHECK (source_row > 0),
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_stats_win_loss_games CHECK (wins + losses = gp),
    CONSTRAINT uq_stats_dataset_player_team UNIQUE (dataset_key, player_id, team_code)
);

-- Table facultative pour une source future réellement au niveau match; reste vide avec les sources actuelles.
CREATE TABLE IF NOT EXISTS matches (
    match_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_date DATE NOT NULL,
    season_label TEXT,
    home_team_code CHAR(3) NOT NULL REFERENCES teams(team_code),
    away_team_code CHAR(3) NOT NULL REFERENCES teams(team_code),
    home_score SMALLINT CHECK (home_score >= 0),
    away_score SMALLINT CHECK (away_score >= 0),
    source_ref TEXT,
    CONSTRAINT ck_matches_distinct_teams CHECK (home_team_code <> away_team_code),
    CONSTRAINT ck_matches_scores_together CHECK ((home_score IS NULL) = (away_score IS NULL)),
    CONSTRAINT uq_matches_fixture UNIQUE (match_date, home_team_code, away_team_code)
);

CREATE TABLE IF NOT EXISTS reports (
    report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_platform TEXT NOT NULL DEFAULT 'Reddit',
    subreddit TEXT NOT NULL,
    post_id TEXT NOT NULL,
    source_url TEXT NOT NULL UNIQUE,
    author TEXT,
    title TEXT NOT NULL,
    body_text TEXT NOT NULL,
    raw_ocr_text TEXT NOT NULL,
    capture_date_text TEXT,
    source_file TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_reports_platform_post UNIQUE (source_platform, post_id),
    CONSTRAINT ck_reports_post_nonblank CHECK (length(btrim(post_id)) > 0)
);

CREATE INDEX IF NOT EXISTS ix_stats_player ON stats(player_id);
CREATE INDEX IF NOT EXISTS ix_stats_team ON stats(team_code);
CREATE INDEX IF NOT EXISTS ix_stats_season ON stats(season_label);
CREATE INDEX IF NOT EXISTS ix_matches_date ON matches(match_date);
CREATE INDEX IF NOT EXISTS ix_matches_season ON matches(season_label);
CREATE INDEX IF NOT EXISTS ix_reports_subreddit ON reports(subreddit);
CREATE INDEX IF NOT EXISTS ix_reports_title_tsv ON reports USING GIN (to_tsvector('english', title || ' ' || body_text));
